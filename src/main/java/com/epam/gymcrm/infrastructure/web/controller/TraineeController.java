package com.epam.gymcrm.infrastructure.web.controller;

import com.epam.gymcrm.application.service.TraineeService;
import com.epam.gymcrm.application.service.TrainingService;
import com.epam.gymcrm.domain.model.Trainee;
import com.epam.gymcrm.domain.model.TraineeTrainingCriteria;
import com.epam.gymcrm.domain.model.User;
import com.epam.gymcrm.infrastructure.web.dto.ActivationRequest;
import com.epam.gymcrm.infrastructure.web.dto.CredentialsResponse;
import com.epam.gymcrm.infrastructure.web.dto.TraineeProfileResponse;
import com.epam.gymcrm.infrastructure.web.dto.TraineeRegistrationRequest;
import com.epam.gymcrm.infrastructure.web.dto.TraineeTrainingResponse;
import com.epam.gymcrm.infrastructure.web.dto.TrainerSummaryResponse;
import com.epam.gymcrm.infrastructure.web.dto.TrainerUsernameRequest;
import com.epam.gymcrm.infrastructure.web.dto.UpdateTraineeRequest;
import com.epam.gymcrm.infrastructure.web.dto.UpdateTraineeTrainersRequest;
import com.epam.gymcrm.infrastructure.web.security.AuthenticatedUser;
import com.epam.gymcrm.infrastructure.web.security.PublicEndpoint;
import jakarta.validation.Valid;
import org.springframework.format.annotation.DateTimeFormat;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PatchMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestAttribute;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.time.LocalDate;
import java.util.List;

import static com.epam.gymcrm.infrastructure.web.security.BasicAuthInterceptor.AUTHENTICATED_USER;

/**
 * Trainee registration, profile, trainers, trainings list and deletion. All methods except
 * registration need a valid Authorization header and work only with the caller's own username.
 */
@RestController
@RequestMapping("/trainees")
public class TraineeController {

    private final TraineeService traineeService;
    private final TrainingService trainingService;

    public TraineeController(TraineeService traineeService, TrainingService trainingService) {
        this.traineeService = traineeService;
        this.trainingService = trainingService;
    }

    /** Registers a trainee; the username and password are generated by the service. */
    @PublicEndpoint
    @PostMapping
    public CredentialsResponse register(@Valid @RequestBody TraineeRegistrationRequest request) {
        Trainee trainee = new Trainee(null,
                User.of(request.firstName(), request.lastName()),
                request.dateOfBirth(),
                request.address());
        User created = traineeService.create(trainee).user();
        return new CredentialsResponse(created.username(), created.password());
    }

    /** The profile of the caller. The interceptor has already checked that the path username is his own. */
    @GetMapping("/{username}")
    public TraineeProfileResponse get(@RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user) {
        return TraineeProfileResponse.from(traineeService.getProfile(user.credentials()));
    }

    @PutMapping("/{username}")
    public TraineeProfileResponse update(@RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user,
                                         @Valid @RequestBody UpdateTraineeRequest request) {
        Trainee changes = new Trainee(null,
                User.of(request.firstName(), request.lastName()),
                request.dateOfBirth(),
                request.address());
        return TraineeProfileResponse.from(
                traineeService.updateProfile(user.credentials(), changes, request.isActive()));
    }

    /** Hard delete: the trainee's trainings are deleted with him. */
    @DeleteMapping("/{username}")
    public void delete(@RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user) {
        traineeService.delete(user.credentials());
    }

    /** Sets the trainee's active flag to the value from the request; repeating the call is harmless. */
    @PatchMapping("/{username}/active")
    public void setActive(@RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user,
                          @Valid @RequestBody ActivationRequest request) {
        traineeService.setActive(user.credentials(), request.isActive());
    }

    /** Active trainers that are not assigned to the trainee yet. */
    @GetMapping("/{username}/not-assigned-trainers")
    public List<TrainerSummaryResponse> notAssignedTrainers(
            @RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user) {
        return traineeService.getNotAssignedTrainers(user.credentials()).stream()
                .map(TrainerSummaryResponse::from)
                .toList();
    }

    /** Replaces the trainee's trainers with the given ones. An empty list removes all of them. */
    @PutMapping("/{username}/trainers")
    public List<TrainerSummaryResponse> updateTrainers(
            @RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user,
            @Valid @RequestBody UpdateTraineeTrainersRequest request) {
        List<String> usernames = request.trainers().stream()
                .map(TrainerUsernameRequest::username)
                .toList();
        return traineeService.updateTrainers(user.credentials(), usernames).stream()
                .map(TrainerSummaryResponse::from)
                .toList();
    }

    /**
     * Trainings of the trainee. All parameters are optional: dates as yyyy-MM-dd, the trainer's
     * first name and the training type name.
     */
    @GetMapping("/{username}/trainings")
    public List<TraineeTrainingResponse> trainings(
            @RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user,
            @RequestParam(name = "periodFrom", required = false)
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate periodFrom,
            @RequestParam(name = "periodTo", required = false)
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate periodTo,
            @RequestParam(name = "trainerName", required = false) String trainerName,
            @RequestParam(name = "trainingType", required = false) String trainingType) {
        TraineeTrainingCriteria criteria =
                new TraineeTrainingCriteria(periodFrom, periodTo, trainerName, trainingType);
        return trainingService.getTraineeTrainings(user.credentials(), criteria).stream()
                .map(TraineeTrainingResponse::from)
                .toList();
    }
}
