package com.epam.gymcrm.infrastructure.web.controller;

import com.epam.gymcrm.application.service.RegisterTrainer;
import com.epam.gymcrm.application.service.TrainerService;
import com.epam.gymcrm.application.service.TrainingService;
import com.epam.gymcrm.domain.model.TrainerTrainingCriteria;
import com.epam.gymcrm.domain.model.User;
import com.epam.gymcrm.infrastructure.web.dto.ActivationRequest;
import com.epam.gymcrm.infrastructure.web.dto.CredentialsResponse;
import com.epam.gymcrm.infrastructure.web.dto.TrainerProfileResponse;
import com.epam.gymcrm.infrastructure.web.dto.TrainerRegistrationRequest;
import com.epam.gymcrm.infrastructure.web.dto.TrainerTrainingResponse;
import com.epam.gymcrm.infrastructure.web.dto.UpdateTrainerRequest;
import com.epam.gymcrm.infrastructure.web.security.AllowInactive;
import com.epam.gymcrm.infrastructure.web.security.PublicEndpoint;
import com.epam.gymcrm.domain.model.AuthenticatedUser;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.enums.ParameterIn;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.format.annotation.DateTimeFormat;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PatchMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestAttribute;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.time.LocalDate;
import java.util.List;

import static com.epam.gymcrm.infrastructure.web.security.BasicAuthInterceptor.AUTHENTICATED_USER;

/**
 * Trainer registration, profile and trainings list. All methods except registration need a valid
 * Authorization header and work only with the caller's own username.
 */
@Tag(name = "Trainers",
        description = "Trainer registration and profile. Except registration, every call needs the "
                + "Authorization: Basic header, and the username in the path must be the caller's own "
                + "(otherwise 403).")
@RestController
@RequestMapping("/trainers")
public class TrainerController {

    private static final String OWN_USERNAME = "Username of the trainer; must be the caller's own";

    private final TrainerService trainerService;
    private final TrainingService trainingService;

    public TrainerController(TrainerService trainerService, TrainingService trainingService) {
        this.trainerService = trainerService;
        this.trainingService = trainingService;
    }

    /** Registers a trainer; the username and password are generated by the service. */
    @Operation(summary = "Register a trainer",
            description = "Public endpoint. The specialization is the id of a training type "
                    + "(see GET /training-types). The generated username and password are returned once.",
            responses = {
                    @ApiResponse(responseCode = "200", description = "Trainer created"),
                    @ApiResponse(responseCode = "400", description = "Invalid body or unknown specialization id")})
    @PublicEndpoint
    @PostMapping
    public CredentialsResponse register(@Valid @RequestBody TrainerRegistrationRequest request) {
        User created = trainerService.register(new RegisterTrainer(request.firstName(), request.lastName(),
                request.specializationId())).user();
        return new CredentialsResponse(created.username(), created.password());
    }

    @Operation(summary = "Get the trainer profile",
            parameters = @Parameter(name = "username", in = ParameterIn.PATH, description = OWN_USERNAME),
            responses = {
                    @ApiResponse(responseCode = "200", description = "Profile with the assigned trainees"),
                    @ApiResponse(responseCode = "401", description = "Missing or wrong credentials"),
                    @ApiResponse(responseCode = "403", description = "Another user's profile or a deactivated account")})
    @GetMapping("/{username}")
    public TrainerProfileResponse get(
            @Parameter(hidden = true) @RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user) {
        return TrainerProfileResponse.from(trainerService.getProfile(user.credentials()));
    }

    @Operation(summary = "Update the trainer profile",
            description = "The username, the password and the specialization are not changed.",
            parameters = @Parameter(name = "username", in = ParameterIn.PATH, description = OWN_USERNAME),
            responses = {
                    @ApiResponse(responseCode = "200", description = "Updated profile"),
                    @ApiResponse(responseCode = "400", description = "Invalid request body"),
                    @ApiResponse(responseCode = "401", description = "Missing or wrong credentials"),
                    @ApiResponse(responseCode = "403", description = "Another user's profile or a deactivated account")})
    @PutMapping("/{username}")
    public TrainerProfileResponse update(
            @Parameter(hidden = true) @RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user,
            @Valid @RequestBody UpdateTrainerRequest request) {
        return TrainerProfileResponse.from(trainerService.updateProfile(
                user.credentials(), request.firstName(), request.lastName(), request.isActive()));
    }

    /** Flips the trainer's active flag on every call (not idempotent). */
    @Operation(summary = "Activate or deactivate the trainer",
            description = "Switches the flag to the opposite value on every call, so repeating the call "
                    + "changes it back. The isActive field is required by the contract, but the new value "
                    + "is always the opposite of the current one.",
            parameters = @Parameter(name = "username", in = ParameterIn.PATH, description = OWN_USERNAME),
            responses = {
                    @ApiResponse(responseCode = "200", description = "Flag switched"),
                    @ApiResponse(responseCode = "400", description = "Invalid request body"),
                    @ApiResponse(responseCode = "401", description = "Missing or wrong credentials"),
                    @ApiResponse(responseCode = "403", description = "Another user's profile or a deactivated account")})
    @PatchMapping("/{username}/active")
    @AllowInactive
    public void toggleActive(
            @Parameter(hidden = true) @RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user,
            @Valid @RequestBody ActivationRequest request) {
        trainerService.toggleActive(user.credentials());
    }

    /** Trainings of the trainer. All parameters are optional: dates as yyyy-MM-dd and the trainee's first name. */
    @Operation(summary = "List the trainer's trainings",
            description = "All filters are optional and can be combined.",
            parameters = @Parameter(name = "username", in = ParameterIn.PATH, description = OWN_USERNAME),
            responses = {
                    @ApiResponse(responseCode = "200", description = "Trainings that match the filters"),
                    @ApiResponse(responseCode = "401", description = "Missing or wrong credentials"),
                    @ApiResponse(responseCode = "403", description = "Another user's profile or a deactivated account")})
    @GetMapping("/{username}/trainings")
    public List<TrainerTrainingResponse> trainings(
            @Parameter(hidden = true) @RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user,
            @Parameter(description = "Trainings from this date, yyyy-MM-dd")
            @RequestParam(name = "periodFrom", required = false)
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate periodFrom,
            @Parameter(description = "Trainings up to this date, yyyy-MM-dd")
            @RequestParam(name = "periodTo", required = false)
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate periodTo,
            @Parameter(description = "First name of the trainee")
            @RequestParam(name = "traineeName", required = false) String traineeName) {
        TrainerTrainingCriteria criteria = new TrainerTrainingCriteria(periodFrom, periodTo, traineeName);
        return trainingService.getTrainerTrainings(user.credentials(), criteria).stream()
                .map(TrainerTrainingResponse::from)
                .toList();
    }
}
