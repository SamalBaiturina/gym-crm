package com.epam.gymcrm.infrastructure.web.controller;

import com.epam.gymcrm.application.service.TrainerService;
import com.epam.gymcrm.application.service.TrainingService;
import com.epam.gymcrm.application.service.TrainingTypeService;
import com.epam.gymcrm.domain.model.Trainer;
import com.epam.gymcrm.domain.model.TrainerTrainingCriteria;
import com.epam.gymcrm.domain.model.TrainingType;
import com.epam.gymcrm.domain.model.User;
import com.epam.gymcrm.infrastructure.web.dto.ActivationRequest;
import com.epam.gymcrm.infrastructure.web.dto.CredentialsResponse;
import com.epam.gymcrm.infrastructure.web.dto.TrainerProfileResponse;
import com.epam.gymcrm.infrastructure.web.dto.TrainerRegistrationRequest;
import com.epam.gymcrm.infrastructure.web.dto.TrainerTrainingResponse;
import com.epam.gymcrm.infrastructure.web.dto.UpdateTrainerRequest;
import com.epam.gymcrm.infrastructure.web.security.AuthenticatedUser;
import com.epam.gymcrm.infrastructure.web.security.PublicEndpoint;
import jakarta.validation.Valid;
import org.springframework.format.annotation.DateTimeFormat;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PatchMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestAttribute;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.time.LocalDate;
import java.util.List;

import static com.epam.gymcrm.infrastructure.web.security.BasicAuthInterceptor.AUTHENTICATED_USER;

/**
 * Trainer registration, profile and trainings list. All methods except registration need a valid
 * Authorization header and work only with the caller's own username.
 */
@RestController
@RequestMapping("/trainers")
public class TrainerController {

    private final TrainerService trainerService;
    private final TrainingTypeService trainingTypeService;
    private final TrainingService trainingService;

    public TrainerController(TrainerService trainerService, TrainingTypeService trainingTypeService,
                             TrainingService trainingService) {
        this.trainerService = trainerService;
        this.trainingTypeService = trainingTypeService;
        this.trainingService = trainingService;
    }

    /** Registers a trainer; the username and password are generated by the service. */
    @PublicEndpoint
    @PostMapping
    public CredentialsResponse register(@Valid @RequestBody TrainerRegistrationRequest request) {
        TrainingType specialization = trainingTypeService.requireById(request.specializationId());
        Trainer trainer = new Trainer(null, User.of(request.firstName(), request.lastName()), specialization);
        User created = trainerService.create(trainer).user();
        return new CredentialsResponse(created.username(), created.password());
    }

    @GetMapping("/{username}")
    public TrainerProfileResponse get(@RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user) {
        return TrainerProfileResponse.from(trainerService.getProfile(user.credentials()));
    }

    @PutMapping("/{username}")
    public TrainerProfileResponse update(@RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user,
                                         @Valid @RequestBody UpdateTrainerRequest request) {
        return TrainerProfileResponse.from(trainerService.updateProfile(
                user.credentials(), request.firstName(), request.lastName(), request.isActive()));
    }

    /** Sets the trainer's active flag to the value from the request; repeating the call is harmless. */
    @PatchMapping("/{username}/active")
    public void setActive(@RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user,
                          @Valid @RequestBody ActivationRequest request) {
        trainerService.setActive(user.credentials(), request.isActive());
    }

    /** Trainings of the trainer. All parameters are optional: dates as yyyy-MM-dd and the trainee's first name. */
    @GetMapping("/{username}/trainings")
    public List<TrainerTrainingResponse> trainings(
            @RequestAttribute(AUTHENTICATED_USER) AuthenticatedUser user,
            @RequestParam(name = "periodFrom", required = false)
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate periodFrom,
            @RequestParam(name = "periodTo", required = false)
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate periodTo,
            @RequestParam(name = "traineeName", required = false) String traineeName) {
        TrainerTrainingCriteria criteria = new TrainerTrainingCriteria(periodFrom, periodTo, traineeName);
        return trainingService.getTrainerTrainings(user.credentials(), criteria).stream()
                .map(TrainerTrainingResponse::from)
                .toList();
    }
}
